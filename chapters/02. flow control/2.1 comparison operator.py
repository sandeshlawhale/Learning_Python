# comparison operator compare two values and evaluate to single boolean values
# ==  Equal to
# !=  Not Equal to
# <   less than
# >   greater than
# <=  less than or equal to
# >=  greater than or equal to

print("42 == 42:")
print(42 == 42)
print("42 != 42:")
print(42 != 42)
print("2 != 3:")
print(2 != 3)
print("2 != 2:")
print(2 != 2)

print("'hello' == 'hello':")
print('hello' == 'hello')
print("'hello' == 'Hello':")
print('hello' == 'Hello')

print("True == True:")
print(True == True)
print("True != False:")
print(True != False)

print("42 == 42.0:")
print(42 == 42.0)
print('42 == "42":')
print(42 == "42")

eggCount = 42
print("eggCount <= 42:")
print(eggCount <= 42)
